"""PostgreSQL adapter for hosting the existing sqlite-based AtolyePanel application.

SQL remains SQLite-compatible in application code. Database-backed deployments use
PostgreSQL's durable storage, transactions and advisory locks.
"""
import re

class MixedRow(dict):
    """sqlite3.Row-compatible key AND position access."""
    def __getitem__(self, key):
        if isinstance(key, int):
            return tuple(self.values())[key]
        return super().__getitem__(key)

class PgResult:
    def __init__(self, cursor, lastrowid=None):
        self.cursor = cursor
        self.lastrowid = lastrowid

    def _row(self, values):
        if values is None:
            return None
        return MixedRow(zip((col.name for col in self.cursor.description), values))

    def fetchone(self):
        return self._row(self.cursor.fetchone())

    def fetchall(self):
        return [self._row(x) for x in self.cursor.fetchall()]

    def __iter__(self):
        for row in self.cursor:
            yield self._row(row)

class PgConnection:
    def __init__(self, url):
        import psycopg
        # Serverless/pooler safe: don't persist named server-side statements.
        self.db = psycopg.connect(url, connect_timeout=10, prepare_threshold=None)

    def execute(self, statement, params=None):
        statement = statement.strip()
        if statement.upper() == 'BEGIN IMMEDIATE':
            # Serialize assignment operations across all serverless instances.
            statement = 'SELECT pg_advisory_xact_lock(39518271)'
        else:
            statement = statement.replace('username=? COLLATE NOCASE', 'LOWER(username)=LOWER(?)')
            statement = statement.replace('?', '%s')
        inserts_card = re.match(r'^INSERT\s+INTO\s+cards\b', statement, re.I) is not None
        if inserts_card:
            statement += ' RETURNING id'
        cursor = self.db.execute(statement, params or ())
        lastrowid = cursor.fetchone()[0] if inserts_card else None
        return PgResult(cursor, lastrowid)

    def commit(self):
        return self.db.commit()

    def rollback(self):
        return self.db.rollback()

    def close(self):
        return self.db.close()


